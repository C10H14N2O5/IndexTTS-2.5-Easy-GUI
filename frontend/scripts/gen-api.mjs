// Regenerate src/api/schema.d.ts from the FastAPI OpenAPI document.
// Usage: pnpm gen:api   (runs ../.venv python -m tools.gui_server.openapi)
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const python = [join(root, '.venv', 'Scripts', 'python.exe'), join(root, '.venv', 'bin', 'python')].find(existsSync) ?? 'python';
const json = execFileSync(python, ['-B', '-m', 'tools.gui_server.openapi'], {
  cwd: root,
  env: { ...process.env, INDEXTTS_FAKE_ENGINE: '1', PYTHONIOENCODING: 'utf-8' },
  maxBuffer: 64 * 1024 * 1024,
  stdio: ['ignore', 'pipe', 'inherit'],
}).toString('utf8');
const start = json.indexOf('{');
const ast = await openapiTS(JSON.parse(json.slice(start)));
const out = join(here, '..', 'src', 'api', 'schema.d.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, '/* eslint-disable */\n// Generated by `pnpm gen:api` from tools/gui_server. Do not edit.\n' + astToString(ast));
console.log(`wrote ${out}`);
